    "                    summary_t = spatial_t.mean(dim=1) if spatial_t.ndim == 3 else spatial_t\n"
    "\n"
    "                summary_vec = summary_t.squeeze(0).float().cpu().numpy()\n"
    "                if spatial_t.ndim == 3:\n"
    "                    spatial_mean = spatial_t.squeeze(0).float().cpu().numpy().mean(axis=0)\n"
    "                else:\n"
