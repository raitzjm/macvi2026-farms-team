    "\n"
    "                if embed_dim is None:\n"
    "                    embed_dim = spatial_mean.shape[0]\n"
    "                    conn.execute(\"INSERT OR IGNORE INTO metadata VALUES (?,?)\", ('embed_dim', str(embed_dim)))\n"
    "                    conn.commit()\n"
    "\n"
    "                batch_data.append((img_name, split, sequence, W, H, blob(summary_vec), blob(spatial_mean)))\n"
    "\n"
    "                if len(batch_data) >= COMMIT_EVERY:\n"
    "                    flush_batch(batch_data, conn)\n"
    "                    batch_data = []\n"
    "\n"
    "            except Exception as exc:\n"
    "                print('ERROR on', img_name, ':', exc)\n"
    "\n"
    "            pbar.update(1)\n"
    "            pbar.set_postfix({'processed': str(i+1) + '/' + str(len(pending))})\n"
    "\n"
    "    if batch_data:\n"
    "        flush_batch(batch_data, conn)\n"
    "    conn.close()\n"
    "\n"
    "    with sqlite3.connect(DB_PATH) as c:\n"
    "        if embed_dim is not None:\n"
    "            c.execute(\"INSERT OR REPLACE INTO metadata VALUES (?,?)\", ('embed_dim', str(embed_dim)))\n"
    "            c.execute(\"INSERT OR REPLACE INTO metadata VALUES (?,?)\", ('model_name', ACTUAL_MODEL))\n"
    "        c.commit()\n"
    "\n"
    "    print('Extraction complete:', count_done(), '/', TOTAL_IMAGES)\n"
