    "from sklearn.preprocessing import normalize as sk_normalize\n"
    "\n"
    "spatial_norm = sk_normalize(spatial_arr, norm='l2')\n"
    "\n"
    "train_mask = (df['split'] == 'train').values\n"
    "val_mask   = (df['split'] == 'val').values\n"
    "test_mask  = (df['split'] == 'test').values\n"
    "\n"
    "train_emb = spatial_norm[train_mask]\n"
    "val_emb   = spatial_norm[val_mask]\n"
    "test_emb  = spatial_norm[test_mask]\n"
    "\n"
    "print('Computing max cosine similarity...')\n"
    "print('val:', val_emb.shape[0], 'test:', test_emb.shape[0], 'vs train:', train_emb.shape[0])\n"
    "\n"
    "\n"
    "def max_cosine_sim(query_emb, ref_emb, chunk=200):\n"
    "    results = []\n"
    "    for i in tqdm(range(0, len(query_emb), chunk), desc='Cosine sim'):\n"
    "        batch = query_emb[i:i+chunk]\n"
    "        sims  = batch @ ref_emb.T\n"
    "        results.append(sims.max(axis=1))\n"
    "    return np.concatenate(results)\n"
    "\n"
    "\n"
    "max_sim_val  = max_cosine_sim(val_emb,  train_emb)\n"
    "max_sim_test = max_cosine_sim(test_emb, train_emb)\n"
    "\n"
    "df.loc[val_mask,  'max_train_sim'] = max_sim_val\n"
    "df.loc[test_mask, 'max_train_sim'] = max_sim_test\n"
    "\n"
    "fig7 = go.Figure()\n"
    "fig7.add_trace(go.Histogram(x=max_sim_val,  name='val',  opacity=0.6, nbinsx=50, marker_color='#ff7f0e'))\n"
    "fig7.add_trace(go.Histogram(x=max_sim_test, name='test', opacity=0.6, nbinsx=50, marker_color='#2ca02c'))\n"
    "fig7.add_vline(x=0.5, line_dash='dash', line_color='red',  annotation_text='0.5')\n"
    "fig7.add_vline(x=0.7, line_dash='dash', line_color='gray', annotation_text='0.7')\n"
    "fig7.update_layout(\n"
    "    barmode='overlay',\n"
    "    title='Max cosine similarity to training set',\n"
    "    xaxis_title='Max cosine similarity',\n"
    "    yaxis_title='Count',\n"
    "    width=850, height=500,\n"
    ")\n"
    "fig7.show()\n"
